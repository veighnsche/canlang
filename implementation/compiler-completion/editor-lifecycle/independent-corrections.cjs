'use strict';
const assert = require('node:assert/strict');
const { fixture, document, tick } = require('../../../editors/vscode/test/client-lifecycle.cjs');
(async () => {
  const checks = [];
  const f = fixture(), c = f.client(), start = c.start(), child = f.children[0];
  child.reply('initialize'); await start;
  let settled = false;
  const pending = c.request('textDocument/hover', {}).then((value) => { assert.equal(value, null); settled = true; });
  const stopped = c.stop(); await tick(); assert(settled);
  checks.push({ case: 'stop immediately cancels pre-existing request', settledBeforeAdvancingClock: settled });
  child.reply('shutdown', null); child.emit('exit', 0); await stopped; await pending;
  checks.push({ case: 'separate shutdown request still responds and cooperative exit finishes stop', kills: child.kills });
  assert.deepEqual(child.kills, []);
  const g = fixture(), d = g.client(), ready = d.start(), ch = g.children[0];
  ch.reply('initialize'); await ready;
  const doc = document(); d.didOpen(doc);
  let cancelled = false;
  const older = d.request('textDocument/hover', {}).then((value) => { assert.equal(value, null); cancelled = true; });
  doc.version = 2; ch.throwWrite = true; d.didChange(doc); await tick();
  assert(!d.isDocumentVersion(doc.uri.toString(), 2)); assert(!d.isDocumentVersion(doc.uri.toString(), 1)); assert(cancelled);
  assert.deepEqual(ch.kills, ['SIGKILL']); assert.equal(g.disposals, 1);
  await assert.rejects(d.request('textDocument/hover', {}), /not ready/); await older;
  checks.push({ case: 'failed document write retires unsent and prior ownership, pending work and admission', ownsUnsentRevision: false, ownsPreviousRevision: false, cancelledImmediately: cancelled, kills: ch.kills });
  const h = fixture(), e = h.client(), begun = e.start(), process = h.children[0];
  process.reply('initialize'); await begun;
  const waiting = e.request('first', {}); process.throwWrite = true;
  await assert.rejects(e.request('initiator', {}), /not running/);
  assert.equal(await waiting, null); assert.equal(h.disposals, 1); assert.deepEqual(process.kills, ['SIGKILL']);
  process.stdin.emit('error', new Error('late EPIPE')); process.emit('exit', 1); assert.equal(h.disposals, 1);
  checks.push({ case: 'failed initiating request rejects; older request cancels; later death/error disposes once', initiatingRequestRejected: true, priorRequestValue: null, disposalCount: h.disposals });
  console.log(JSON.stringify(checks, null, 2));
})().catch((error) => { console.error(error); process.exitCode = 1; });
