/** Pure proleptic-Gregorian civil rules shared by values and temporal callers. */

/** Days from 1970-01-01; internal probe years may lie outside public date bounds. */
export function daysFromCivil(year: number, month: number, day: number): number {
  const yAdj = month <= 2 ? year - 1 : year;
  const era = Math.floor(yAdj / 400);
  const yoe = yAdj - era * 400;
  const mp = (month + 9) % 12;
  const doy = Math.floor((153 * mp + 2) / 5) + day - 1;
  const doe = yoe * 365 + Math.floor(yoe / 4) - Math.floor(yoe / 100) + doy;
  return era * 146097 + doe - 719468;
}

export function isLeapYear(year: number): boolean {
  return year % 4 === 0 && (year % 100 !== 0 || year % 400 === 0);
}

export function daysInMonth(year: number, month: number): number {
  switch (month) {
    case 1:
    case 3:
    case 5:
    case 7:
    case 8:
    case 10:
    case 12:
      return 31;
    case 4:
    case 6:
    case 9:
    case 11:
      return 30;
    case 2:
      return isLeapYear(year) ? 29 : 28;
    default:
      return 0;
  }
}
