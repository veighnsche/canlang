/**
 * Emits owner-derived currency facts for the native semantics core (A03.4).
 *
 * Reads the owning `currency-data.ts` source (never a second table) and the
 * owning catalog emission, then writes a reproducible Rust facts module plus
 * a JSON manifest with provenance. Drift detection runs in the differential
 * (`conformance/ports/exact/differential.mjs`): 165 admitted currencies,
 * excluded codes, scales 0/2/3/4, export availability.
 *
 * Usage: node packages/values/scripts/emit-semantics-inputs.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const pkg = join(here, "..");
const ownerSource = join(pkg, "src", "currency-data.ts");
const catalogSource = join(pkg, "src", "catalog.ts");
const outRs = join(pkg, "semantics", "src", "currency_facts.rs");
const outJson = join(pkg, "semantics", "currency-facts.json");

const text = readFileSync(ownerSource, "utf8");
const entry = /^  ([A-Z]{3}): (\d),$/gm;
const rows = [];
let match = entry.exec(text);
while (match !== null) {
  rows.push([match[1], Number(match[2])]);
  match = entry.exec(text);
}
rows.sort((a, b) => (a[0] < b[0] ? -1 : 1));

const scales = new Set(rows.map(([, scale]) => scale));
const counts = {};
for (const [, scale] of rows) counts[scale] = (counts[scale] ?? 0) + 1;

const manifest = {
  provenance: {
    owner: "packages/values/src/currency-data.ts",
    catalog: "packages/values/src/catalog.ts",
    publication: 'ISO 4217 list-one.xml Pblshd="2026-09-17" via owning source header',
    note: "Generated; never hand-edited. Drift-checked by the differential against owning sources.",
  },
  admitted: rows.length,
  scales: [...scales].sort(),
  counts,
  excluded: ["XAG", "XAU", "XBA", "XBB", "XBC", "XBD", "XDR", "XPD", "XPT", "XSU", "XTS", "XUA", "XXX"],
  currencies: Object.fromEntries(rows),
};

const catalogText = readFileSync(catalogSource, "utf8");
if (!/185|165/.test(catalogText) && rows.length !== 165) {
  throw new Error(`expected 165 admitted currencies, found ${rows.length}`);
}
if (rows.length !== 165) {
  throw new Error(`expected 165 admitted currencies, found ${rows.length}`);
}

const rsRows = rows.map(([code, scale]) => `    ("${code}", ${scale}),`).join("\n");
const rs = `//! Owner-derived currency facts (generated by scripts/emit-semantics-inputs.mjs).
//!
//! Provenance: ISO 4217 list-one.xml Pblshd="2026-09-17" via
//! \`packages/values/src/currency-data.ts\`. Never hand-edited; drift is
//! detected by the differential against the owning sources.

/// Admitted currencies with pinned minor-unit scales, sorted by code.
pub const CURRENCY_FACTS: [(&str, u8); 165] = [
${rsRows}
];

/// Pinned-table lookup: minor-unit scale for an admitted code.
pub fn currency_table_scale(code: &str) -> Option<u8> {
    // Sorted table; binary search keeps the generated file dependency-free.
    let mut lo = 0usize;
    let mut hi = CURRENCY_FACTS.len();
    while lo < hi {
        let mid = lo + (hi - lo) / 2;
        let (candidate, scale) = CURRENCY_FACTS[mid];
        if candidate == code {
            return Some(scale);
        } else if candidate < code {
            lo = mid + 1;
        } else {
            hi = mid;
        }
    }
    None
}
`;

writeFileSync(outRs, rs);
writeFileSync(outJson, `${JSON.stringify(manifest, null, 2)}\n`);
console.log(`currency facts: ${rows.length} admitted, scales ${[...scales].sort().join("/")} -> semantics/src/currency_facts.rs`);
