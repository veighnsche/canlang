fn check_build(id: &str, roots: &[ScannedRoot], expected: Result<DistManifest, Option<&str>>) {
    let got = build_dist_manifest(roots);
    match (got, expected) {
        (Ok(manifest), Ok(want)) => assert_eq!(manifest, want, "{id}"),
        (Err(message), Ok(_)) => panic!("{id}: native refused, TS built:\n{message}"),
        (Ok(_), Err(_)) => panic!("{id}: native built, TS refused"),
        (Err(message), Err(Some(want))) => assert_eq!(message, want, "{id}"),
        (Err(_), Err(None)) => panic!("{id}: unreachable"),
    }
}

