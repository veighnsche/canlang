//! Release differential (P04.3): every vector ran through the real
//! `assertLockstep` / `buildDistManifest` / `verifyDistManifest` /
//! `verifyExecutableManifest`. TS message expectations pass through the
//! stdout UTF-8 boundary (unpaired surrogates -> U+FFFD), the same
//! boundary native `render_text` emits; manifests/paths compare as
//! lossless UTF-16 units. Regenerate with `bun /tmp/p043-vectors.ts`
//! plus this emitter.
use can_preparation::input::Node;
use can_preparation::release::*;

#[allow(clippy::too_many_arguments)]
fn check_lockstep(
    id: &str,
    root: &[u16],
    platform: &[u16],
    compiler: &[u16],
    contracts_bits: u64,
    contracts_spelling: &str,
    packages: &[(&[u16], &[u16])],
    expected: Option<&str>,
) {
    let got = assert_lockstep(&LockstepInputs {
        root_version: root,
        platform_version: platform,
        compiler_version: compiler,
        contracts_version: f64::from_bits(contracts_bits),
        contracts_spelling,
        package_versions: packages.to_vec(),
    });
    match (got, expected) {
        (Ok(()), None) => {}
        (Err(message), Some(want)) => assert_eq!(message, want, "{id}"),
        (Ok(()), Some(want)) => panic!("{id}: native ok, TS refused:\n{want}"),
        (Err(message), None) => panic!("{id}: native refused, TS ok:\n{message}"),
    }
}

